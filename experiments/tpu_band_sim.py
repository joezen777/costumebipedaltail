"""Simulate the Barney tail with the TPU strap pairs in place of the extension springs.

    PYTHONPATH=. python experiments/tpu_band_sim.py

Cases: as-built springs; straps as designed (linearised at rest: same T0, k from cad/tpu_bands.py);
straps with the material 30 % softer / 30 % stiffer than assumed (rest pose re-trimmed, so T0 is kept and only
k is off). Writes docs/tables/tpu_band_sim.md.
"""
import json
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from experiments.barney import configs, MOTIONS
from tailsim.metrics import evaluate
from tailsim.sim import TailSim

ROOT = Path(__file__).resolve().parents[1]
CASES = ("springs", "straps", "straps_k-30%", "straps_k+30%")
RUN = ("hip_snap_30", "dramatic_turn_45", "walk_1.50Hz", "jump", "crouch")


def params(case):
    p = configs()["as_built"]
    if case == "springs":
        return p
    straps = json.loads((ROOT / "cad" / "stl" / "barney_tpu_bands" / "straps.json").read_text())["straps"]
    by = {(s["joint"], s["side"]): s for s in straps}
    f = {"straps": 1.0, "straps_k-30%": 0.7, "straps_k+30%": 1.3}[case]
    order = [(s["joint"] + 1, s["side"]) for s in TailSim(p, settle=False).spring]
    return p.variant(spring_override=[{"k": by[o]["k_pair"] * 1000 * f, "T0": by[o]["T0_pair"]} for o in order])


def job(a):
    case, m = a
    return case, m, evaluate(TailSim(params(case)).run(MOTIONS[m]()))


def main():
    res = {c: {} for c in CASES}
    with ProcessPoolExecutor(4) as ex:
        for c, m, r in ex.map(job, [(c, m) for c in CASES for m in RUN]):
            res[c][m] = r
    rows = []
    for c in CASES:
        s, t, w, j, cr = (res[c][m] for m in RUN)
        rows.append(f"| {c} | {s['maximum_tip_lag']:.0f}° | {s['maximum_tip_overshoot']:.0f}° | {s['oscillation_count']} | "
                    f"{s['settling_time']:.2f} s | {t['maximum_tip_overshoot']:.0f}° | {w['whip_ratio']:.2f} | "
                    f"{s['rest_floor_clearance'] * 100:.0f} cm | {cr['min_floor_clearance'] * 100:.0f} cm | "
                    f"{j['max_floor_force']:.0f} N | {max(s['peak_root_moment'], j['peak_root_moment']):.1f} N·m |")
    txt = ("# Barney tail: TPU straps vs extension springs (as built, MuJoCo)\n\n"
           "Generated by experiments/tpu_band_sim.py. Straps are linearised at rest (T0 and k from cad/tpu_bands.py). "
           "The ±30 % rows model a material stiffer or softer than assumed after the rest pose is re-trimmed with the "
           "tight variants, so only k is off. TPU hysteresis (extra damping) is not modelled, so overshoot here is "
           "conservative.\n\n"
           "| case | snap lag | snap overshoot | swings | settle | 45° turn overshoot | walk tip/hip | rest clearance | "
           "crouch clearance | jump floor force | peak belt moment |\n|---|---|---|---|---|---|---|---|---|---|---|\n"
           + "\n".join(rows) + "\n")
    (ROOT / "docs" / "tables" / "tpu_band_sim.md").write_text(txt)
    print(txt)


if __name__ == "__main__":
    main()
