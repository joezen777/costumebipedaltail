"""Simulate the Barney tail with the TPU strap pairs in place of the extension springs.

    PYTHONPATH=. python experiments/tpu_band_sim.py

Cases: as-built springs; the straps in cad/stl/barney_tpu_bands/straps.json linearised at rest (same T0, k from
the strap model) or with the secant rate from rest to the stop (95A softens past its knee); seat friction for a
felt liner (MEDIUM), a TPU liner (HIGH) or bare PETG (LOW); material 30 % softer / stiffer than assumed
(rest pose re-trimmed, so only k is off). Writes docs/tables/tpu_band_sim.md.
"""
import json
import math
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from experiments.barney import configs, MOTIONS
from tailsim.metrics import evaluate
from tailsim.sim import TailSim

ROOT = Path(__file__).resolve().parents[1]
# (label, strap stiffness model, seat friction level)
CASES = (("springs, felt seat liner", None, "MEDIUM"),
         ("95A straps, felt seat liner", "tangent", "MEDIUM"),
         ("95A straps (secant rate to the stop), felt", "secant", "MEDIUM"),
         ("95A straps, TPU seat liner", "tangent", "HIGH"),
         ("95A straps, bare PETG seat + TPU cap cushion", "tangent", "LOW"),
         ("95A straps k-30 %, felt", 0.7, "MEDIUM"),
         ("95A straps k+30 %, felt", 1.3, "MEDIUM"))
RUN = ("hip_snap_30", "dramatic_turn_45", "walk_1.50Hz", "jump", "crouch")


def params(case):
    _, model, fric = case
    p = configs()["as_built"].variant(friction=fric)
    if model is None:
        return p
    straps = json.loads((ROOT / "cad" / "stl" / "barney_tpu_bands" / "straps.json").read_text())["straps"]
    by = {(s["joint"], s["side"]): s for s in straps}
    sim = TailSim(p, settle=False)
    lims = {"L": p.yaw_limit_list(), "R": p.yaw_limit_list(), "D": p.pitch_limit_list()}
    over = []
    for sp in sim.spring:
        s = by[(sp["joint"] + 1, sp["side"])]
        k = s["k_pair"]
        if model == "secant":           # TPU softens past its knee: average rate from rest to the stop
            dl = s["arm"] * math.radians(lims[sp["side"]][sp["joint"]])
            k = (s["T_stop_pair"] - s["T0_pair"]) / dl
        elif isinstance(model, float):
            k *= model
        over.append({"k": k * 1000, "T0": s["T0_pair"]})
    return p.variant(spring_override=over)


def job(a):
    ci, m = a
    return ci, m, evaluate(TailSim(params(CASES[ci])).run(MOTIONS[m]()))


def main():
    res = {ci: {} for ci in range(len(CASES))}
    with ProcessPoolExecutor(4) as ex:
        for ci, m, r in ex.map(job, [(ci, m) for ci in range(len(CASES)) for m in RUN]):
            res[ci][m] = r
    rows = []
    for ci, c in enumerate(CASES):
        s, t, w, j, cr = (res[ci][m] for m in RUN)
        rows.append(f"| {c[0]} | {s['maximum_tip_lag']:.0f}° | {s['maximum_tip_overshoot']:.0f}° | {s['oscillation_count']} | "
                    f"{s['settling_time']:.2f} s | {t['maximum_tip_overshoot']:.0f}° | {w['whip_ratio']:.2f} | "
                    f"{s['rest_floor_clearance'] * 100:.0f} cm | {cr['min_floor_clearance'] * 100:.0f} cm | "
                    f"{j['max_floor_force']:.0f} N | {max(s['peak_root_moment'], j['peak_root_moment']):.1f} N·m |")
    txt = ("# Barney tail: TPU straps vs extension springs (as built, MuJoCo)\n\n"
           "Generated by experiments/tpu_band_sim.py from the current straps.json. Straps are linearised at rest (T0 "
           "and k from cad/tpu_bands.py) or with the secant rate to the stop. Seat friction: felt liner mu 0.25, TPU "
           "liner mu 0.45, bare PETG mu 0.12 (tailsim FRICTION_LEVELS). The ±30 % rows model a material stiffer or "
           "softer than assumed after the rest pose is re-trimmed. TPU hysteresis (extra damping) is not modelled.\n\n"
           "| case | snap lag | snap overshoot | swings | settle | 45° turn overshoot | walk tip/hip | rest clearance | "
           "crouch clearance | jump floor force | peak belt moment |\n|---|---|---|---|---|---|---|---|---|---|---|\n"
           + "\n".join(rows) + "\n")
    (ROOT / "docs" / "tables" / "tpu_band_sim.md").write_text(txt)
    print(txt)


if __name__ == "__main__":
    main()
