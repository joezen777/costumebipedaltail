"""CAD assembly renders of the Gojira tail on a performer in the five simulated poses.

Unlike experiments/pose_renders.py (smooth skin tube), these draw the actual exported
print STLs (cad/stl/barney/) articulated with the simulated per-joint yaw/pitch/roll and
pelvis pose, with a translucent skin envelope and a posed performer.

    PYTHONPATH=. python experiments/cad_pose_renders.py
"""
import math
import pickle
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments.pose_renders import pick, frame_at, rot, CAMS  # noqa: E402

OUT = ROOT / "results" / "cad_renders_barney"
POSES = ROOT / "cad" / "openscad" / "poses"
PZ = 0.55 * 1.727        # pelvis height (m) = origin of the CAD pelvis frame


def mannequin(pelvis, ypr_deg, pose):
    """Capsules (a, b, r) in metres, world frame: a bulky suit performer."""
    yaw, pitch, roll = [math.radians(x) for x in ypr_deg]
    R, Ry = rot(yaw, pitch, roll), rot(yaw, 0)
    P = np.asarray(pelvis)
    L = lambda v: P + R @ np.asarray(v)
    caps = [(L([0, -0.08, 0.02]), L([0, 0.08, 0.02]), 0.15),          # hips
            (L([0.0, 0, 0.1]), L([0.02, 0, 0.40]), 0.19),              # torso
            (L([0.02, 0, 0.45]), L([0.08, 0, 0.62]), 0.10),            # neck
            (L([0.08, 0, 0.72]), L([0.24, 0, 0.70]), 0.09)]            # head / snout
    # lumbar support belt (ring of capsules at the mount height)
    ring = [L([0.19 * math.cos(t), 0.24 * math.sin(t), 0.05]) for t in np.linspace(0, 2 * math.pi, 13)]
    caps += [(a, b, 0.035) for a, b in zip(ring[:-1], ring[1:])]
    for side in (1, -1):
        hip = L([0.0, 0.10 * side, -0.05])
        if pose == "jump":
            knee = hip + Ry @ np.array([0.10, 0.02 * side, -0.40])
            foot = knee + Ry @ np.array([-0.08, 0.0, -0.40])
        else:
            foot = np.array([hip[0] + (0.05 if pose != "bend" else 0.12) * math.cos(yaw), hip[1] + 0.03 * side, 0.06])
            knee = 0.5 * (hip + foot) + Ry @ np.array([0.05 if pose != "bend" else 0.12, 0, 0])
        caps += [(hip, knee, 0.10), (knee, foot, 0.08), (foot, foot + Ry @ np.array([0.20, 0, -0.02]), 0.065)]
        sh = L([0.02, 0.22 * side, 0.46])
        if pose == "jump":
            el = sh + R @ np.array([0.15, 0.08 * side, 0.12]); hand = el + R @ np.array([0.22, 0.02 * side, 0.05])
        else:
            el = sh + R @ np.array([0.10, 0.06 * side, -0.24]); hand = el + R @ np.array([0.20, 0.0, -0.05])
        caps += [(sh, el, 0.065), (el, hand, 0.055)]
    return caps


def fmt(v):
    return "[" + ", ".join(f"{x:.3f}" for x in v) + "]"


def write_pose(name, fr, r_idx, raw_r, pose):
    k = r_idx
    yaw, pitch, roll = raw_r["yaw"][k], raw_r["pitch"][k], raw_r["roll"][k]
    pel = (np.asarray(fr["pelvis_pos"]) - [0, 0, PZ]) * 1000
    caps = mannequin(fr["pelvis_pos"], fr["pelvis_ypr"], pose)
    to_cad = lambda p: (np.asarray(p) - [0, 0, PZ]) * 1000
    man = ", ".join(f"[{fmt(to_cad(a))}, {fmt(to_cad(b))}, {r*1000:.1f}]" for a, b, r in caps)
    POSES.mkdir(parents=True, exist_ok=True)
    f = POSES / f"{name}.scad"
    f.write_text(f"""// generated by experiments/cad_pose_renders.py: simulated pose '{name}' at t = {fr['t']:.3f} s
include <../render_views_barney.scad>
STL = "{(ROOT / 'cad' / 'stl' / 'barney').as_posix()}/";
VIEW = "pose";
POSE_YAW = {fmt(yaw)};
POSE_PITCH = {fmt(pitch)};
POSE_ROLL = {fmt(roll)};
PELVIS_POS = {fmt(pel)};
PELVIS_YPR = {fmt(fr['pelvis_ypr'])};
MANNEQUIN = [{man}];
""")
    return f


def render(args):
    name, f = args
    ex, ey, ez, tx, ty, tz = CAMS[name]
    k = 1.75                                    # OpenSCAD's lens is narrower than MuJoCo's: back off
    ex, ey, ez = tx + k * (ex - tx), ty + k * (ey - ty), tz + k * (ez - tz)
    cam = ",".join(f"{v:.0f}" for v in [ex * 1000, ey * 1000, (ez - PZ) * 1000, tx * 1000, ty * 1000, (tz - PZ) * 1000])
    cmd = ["openscad", "-o", str(OUT / f"{name}.png"), "--imgsize=1600,1000", f"--camera={cam}",
           "--colorscheme=Tomorrow", "--projection=p", str(f)]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=f.parent)
    return name, r.returncode, r.stderr[-300:] if r.returncode else ""


def main():
    raw = pickle.load(open(ROOT / "scratch" / "barney_raw.pkl", "rb"))["as_built"]
    OUT.mkdir(parents=True, exist_ok=True)
    jobs = []
    for name, (r, t, pose) in pick(raw).items():
        fr = frame_at(r, t)
        k = int(round(t / (r["time"][1] - r["time"][0])))
        jobs.append((name, write_pose(name, fr, min(k, len(r["time"]) - 1), r, pose)))
    with ThreadPoolExecutor(3) as ex:
        for name, rc, err in ex.map(render, jobs):
            print(name, "ok" if rc == 0 else f"rc={rc} {err}")


if __name__ == "__main__":
    main()
