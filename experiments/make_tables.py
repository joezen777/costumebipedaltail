"""Generate markdown tables for docs/ from the model and results/data.

    PYTHONPATH=. ~/.venvs/costumebipedaltail/bin/python experiments/make_tables.py
"""
import json
import math
from pathlib import Path

import numpy as np

from cad import geometry as g
from tailsim.params import TailParams
from tailsim.sim import TailSim
from tailsim.mass_budget import budget

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "results" / "data"
OUT = ROOT / "docs" / "tables"
PETG_ALLOW = 20.0      # MPa, interlayer-safe allowable for 1.2 mm nozzle PETG
PETG_UTS = 45.0


def md(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
    for r in rows:
        s += "| " + " | ".join(str(x) for x in r) + " |\n"
    return s


def springs(sim, p, c):
    rows = []
    for s in sim.spring:
        i = s["joint"] + 1
        lim = p.yaw_limit_list()[i - 1] if s["side"] in "LR" else p.pitch_limit_list()[i - 1]
        Tmax = s["T0"] + s["k"] * s["arm"] * math.radians(lim)
        L_inst = g.spring_span_parent(c, i) + g.spring_span_child(c)
        rows.append([f"J{i}", {"L": "left", "R": "right", "D": "dorsal"}[s["side"]], f"{s['k']/1000:.2f}",
                     f"{s['T0']:.1f}", f"{Tmax:.1f}", f"{s['arm']*1000:.1f}", f"{L_inst:.1f}",
                     f"{g.coil_od(c, i):.1f}"])
    return md(["joint", "spring", "rate k (N/mm)", "tension at rest T0 (N)", "tension at stop (N)",
               "moment arm (mm)", "installed length (mm)", "max coil OD (mm)"], rows)


def strength(p, c, study):
    ref = study["reference"]
    rows = []
    worst = {}
    for key in ("hip_snap_30", "dramatic_turn_45", "walk_1.50Hz", "crouch", "side_step_300mm"):
        pass
    names = [k for k in ref if isinstance(ref[k], dict) and "peak_neck_moment" in ref[k]]
    peak_neck = max(ref[k]["peak_neck_moment"] for k in names)
    peak_stop = max(ref[k]["peak_stop_torque"] for k in names)
    for i in range(1, p.n + 1):
        Z = g.neck_section_modulus(c, i)
        M_allow = PETG_ALLOW * Z / 1000                     # N*m
        rows.append([f"J{i}", f"{2*g.RN(c, i):.1f} / {2*g.bore_r(c):.0f}", f"{Z:.0f}", f"{M_allow:.1f}"])
    return md(["joint", "neck OD / bore (mm)", "section modulus (mm³)", "allowable moment @20 MPa (N·m)"], rows), peak_neck, peak_stop


HEAD = ["configuration", "snap lag", "snap overshoot", "oscillations", "settle", "residual", "turn overshoot",
        "walk whip 1.5/2.0", "peak tip v", "max roll", "crouch min tip z", "crouch floor N", "lowest mode Hz", "score"]


def study_rows(study, keys):
    rows = []
    for k, label in keys:
        if k not in study:
            continue
        s, t, w, w2 = study[k]["hip_snap_30"], study[k]["dramatic_turn_45"], study[k]["walk_1.50Hz"], study[k]["walk_2.00Hz"]
        cr = study[k]["crouch"]
        rows.append([label, f"{s['maximum_tip_lag']:.1f}", f"{s['maximum_tip_overshoot']:.1f}", s["oscillation_count"],
                     f"{s['settling_time']:.2f}", f"{s['residual_offset']:.1f}", f"{t['maximum_tip_overshoot']:.1f}",
                     f"{w['whip_ratio']:.2f} / {w2['whip_ratio']:.2f}", f"{s['peak_tip_velocity']:.2f}",
                     f"{s['maximum_joint_roll']:.1f}", f"{cr['min_tip_height']:.2f}", f"{cr['max_floor_force']:.1f}",
                     f"{study[k]['linear']['lowest_mode_hz']:.3f}", f"{study[k]['score']:.1f}"])
    return rows


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    p = TailParams()
    c = p.cad()
    sim = TailSim(p, settle=False)
    (OUT / "springs.md").write_text("# Spring schedule (reference design)\n\n"
                                    "Generated by experiments/make_tables.py from the physics spring design.\n"
                                    "Buy extension springs with the listed rate whose force at the installed length equals T0;\n"
                                    "parallel pairs are fine (halve k and T0 each). Adjust T0 with a short cord loop on the hook.\n\n"
                                    + springs(sim, p, c))
    study = json.loads((DATA / "study_metrics.json").read_text())
    # per-joint peak loads from the reference runs
    from tailsim import motions
    from tailsim.metrics import evaluate
    peak = dict(neck=np.zeros(p.n), stop=np.zeros(p.n), N=np.zeros(p.n), Nlat=np.zeros(p.n), springT=np.zeros(len(sim.spring)))
    import sys
    sys.path.insert(0, str(ROOT / "experiments"))
    from run_suite import hardware_configs
    built = hardware_configs()["as_built"]                  # CAD masses, as-built springs
    for mo in motions.standard_tests():
        r = TailSim(built).run(mo)
        peak["neck"] = np.maximum(peak["neck"], r["peak_neck_moment"])
        peak["stop"] = np.maximum(peak["stop"], r["peak_stop_torque"])
        peak["N"] = np.maximum(peak["N"], r["joint_force"].max(0))
        lat = np.sqrt(np.maximum(r["joint_force"] ** 2 - r["seat_comp"] ** 2, 0))
        peak["Nlat"] = np.maximum(peak["Nlat"], lat.max(0))
        peak["springT"] = np.maximum(peak["springT"], r["spring_T"].max(0))
    rows = []
    for i in range(1, p.n + 1):
        Z = g.neck_section_modulus(c, i)
        M_allow = PETG_ALLOW * Z / 1000
        M_design = peak["neck"][i-1] + peak["Nlat"][i-1] * g.DF(c, i) / 1000    # ball moment + lateral ball force x neck length
        Td = max(s for s, sp in zip(peak["springT"], sim.spring) if sp["joint"] == i - 1)
        ear_M = Td * (g.spring_arm(c, i) - g.cap_outer_r(c, i)) / 1000
        ear_Z = g.ear_w(c, i) * g.cap_ear_t(c) ** 2 / 6
        ear_sigma = ear_M * 1000 / ear_Z
        rows.append([f"J{i}", f"{peak['neck'][i-1]:.2f}", f"{peak['N'][i-1]:.0f} / {peak['Nlat'][i-1]:.0f}", f"{M_design:.2f}", f"{M_allow:.1f}",
                     f"{M_allow / max(M_design, 1e-6):.1f}", f"{Td:.0f}", f"{ear_sigma:.1f}", f"{PETG_UTS / ear_sigma:.1f}"])
    (OUT / "strength.md").write_text(
        "# Strength check (as-built tail: CAD masses, all standard motion tests)\n\n"
        "Neck design moment = peak moment carried through the ball (friction + stop) + peak *lateral* ball force x neck length "
        "(peak moment and peak force are combined even if they occur at different instants, which is conservative; the axial "
        "seat compression from the spring preload does not bend the neck). Allowable = 20 MPa on the hollow neck section "
        "(layers run along the neck in the clamshell ball halves). Cap ear: dorsal/lateral spring peak tension as an "
        "out-of-plane cantilever load on the 10 mm ear, compared with PETG UTS 45 MPa.\n\n"
        + md(["joint", "peak ball moment (N·m)", "peak ball force total / lateral (N)", "neck design moment (N·m)", "neck allowable (N·m)",
              "neck SF", "peak spring tension (N)", "ear stress (MPa)", "ear SF vs UTS"], rows))
    rows = []
    for r, ref in zip(budget(c, sim.spring_table()), [450, 400, 330, 270, 210, 160, 110, 70]):
        rows.append([f"V{r['i']}", f"{r['printed_g']:.0f}", f"{r['hardware_g']:.0f}", f"{r['springs_g']:.0f}",
                     f"{r['foam_g']:.0f}", f"{r['skin_g']:.0f}", f"**{r['total_g']:.0f}**", ref])
    (OUT / "mass_budget.md").write_text("# Moving-mass budget per segment (grams)\n\nPrinted masses from the exported STLs "
                                        "(3 perimeters of 1.3 mm solid, 20 % core infill, PETG 1.27 g/cm³).\n\n"
                                        + md(["segment", "printed", "hardware", "springs", "foam", "skin", "total", "README target"], rows))
    # study summary
    keys = [("A_friction_only", "A friction only"), ("B_cord_preload", "B + cord preload"), ("C_offset_com", "C + offset COM"),
            ("D_progressive", "D + progressive limits"), ("reference", "reference (= D, tuned)"), ("cad_masses", "reference, CAD masses"),
            ("naive_no_springs", "naive: no springs"), ("D_roll_unrestricted", "D, roll unrestricted")]
    keys += [(k, k) for k in study if k.startswith(("com_", "preload_", "friction_", "joints_", "mass_", "limits_"))]
    rows = study_rows(study, keys)
    (OUT / "study.md").write_text(
        "# Configuration study (identical hip inputs)\n\nHip snap = 30° in 0.35 s; turn = 45° in 0.5 s; walk = ±5° yaw, ±3° roll, "
        "±20 mm bob at 1.5 and 2.0 steps/s. Angles in degrees, times in s, velocity in m/s, heights in m. Lowest mode: "
        "smallest small-motion frequency about the rest pose (negative = statically unstable). Score: penalty vs the README "
        "target bands (lower = closer; see tailsim/metrics.py).\n\n"
        + md(HEAD, rows))
    hw = DATA / "hardware_metrics.json"
    if hw.exists():
        h = json.loads(hw.read_text())
        labels = {"as_built": "as built (CAD masses, cord 10 N, felt, COM 15 mm)"}
        keys = [(k, labels.get(k, k.replace("hw_", "as built, ").replace("_", " "))) for k in h]
        (OUT / "hardware.md").write_text(
            "# Same built tail, one setting changed\n\nSprings frozen at the as-built design (CAD masses); only the listed "
            "setting changes, as a builder would adjust it backstage. Columns as in study.md.\n\n" + md(HEAD, study_rows(h, keys)))
    print("tables written")


if __name__ == "__main__":
    main()
